test('installPinProblems checks every install line against the Verified versions', () => {
  const fence = (lines) => `${VERIFIED}\n\n\`\`\`bash\n${lines}\n\`\`\`\n`;
  const check = (lines) => contract.installPinProblems(fence(lines));
  assert.deepEqual(check('pip install openai==2.3.0'), []);
  assert.deepEqual(check('pip install "openai[extra]==2.3.0"'), []);
  assert.deepEqual(check('uv add openai==2.3.0'), []);
  assert.deepEqual(check('npm install openai@2.3.0'), []);
  assert.deepEqual(check('pnpm add openai@2.3.0'), []);
  assert.deepEqual(check('npm install --save-exact openai@2.3.0'), []);
  assert.deepEqual(check('pip install -r requirements.txt'), []);
  assert.deepEqual(check('pip install openai'), ['install line "pip install openai": openai is not pinned']);
  assert.deepEqual(check('pip install openai==2.2.0'), [
    'install line "pip install openai==2.2.0": openai is pinned to 2.2.0, but <Verified> says 2.3.0',
  ]);
  assert.deepEqual(check('npm install langchain@0.3.0'), [
    'install line "npm install langchain@0.3.0": langchain is not listed in <Verified>',
  ]);
  assert.deepEqual(check('npm install @ai-sdk/openai@2.3.0'), [
    'install line "npm install @ai-sdk/openai@2.3.0": @ai-sdk/openai is not listed in <Verified>',
  ]);
  // Prose and install commands outside a code fence are not checked.
  assert.deepEqual(contract.installPinProblems(`${VERIFIED}\n\nRun pip install openai first.\n`), []);
  // Package names compare the way pip does: case and the - _ . separators do not matter.
  assert.deepEqual(
    contract.installPinProblems(
      "<Verified date=\"2026-10-14\" packages={[{ name: 'opentelemetry-sdk', version: '1.38.0' }]} />\n\n```bash\npip install opentelemetry_sdk==1.38.0\n```\n",
    ),
    [],
  );
});

test('installPinProblems keeps a PyPI package and an npm package of the same name apart', () => {
  const verified =
    "<Verified date=\"2026-10-14\" packages={[{ name: 'openai (Python)', version: '3.22.0' }, { name: 'openai (npm)', version: '7.25.0' }]} />";
  const check = (lines) => contract.installPinProblems(`${verified}\n\n\`\`\`bash\n${lines}\n\`\`\`\n`);
  assert.deepEqual(check('pip install openai==3.22.0\nnpm install openai@7.25.0'), []);
  assert.deepEqual(check('pip install openai==7.25.0'), [
    'install line "pip install openai==7.25.0": openai is pinned to 7.25.0, but <Verified> says 3.22.0',
  ]);
  assert.deepEqual(check('npm install openai@3.22.0'), [
    'install line "npm install openai@3.22.0": openai is pinned to 3.22.0, but <Verified> says 7.25.0',
  ]);
});

test('installPinProblems sees continued lines, chained commands and package-manager aliases', () => {
  const fence = (lines) => `${VERIFIED}\n\n\`\`\`bash\n${lines}\n\`\`\`\n`;
  const check = (lines) => contract.installPinProblems(fence(lines));
  const unpinned = (command, name = 'openai') => [`install line "${command}": ${name} is not pinned`];

  // A backslash continuation joins the next lines into one command.
  assert.deepEqual(check('pip install \\\n  openai \\\n  anthropic==0.45.0'), [
    'install line "pip install openai anthropic==0.45.0": openai is not pinned',
    'install line "pip install openai anthropic==0.45.0": anthropic is not listed in <Verified>',
  ]);
  assert.deepEqual(check('pip install \\\n  openai==2.3.0'), []);

  // Every install command on a line counts, not only the first.
  assert.deepEqual(check('pip install openai==2.3.0 && pip install foo'), unpinned('pip install foo', 'foo'));
  assert.deepEqual(check('pip install openai==2.3.0; pip install foo==1.0.0'), [
    'install line "pip install foo==1.0.0": foo is not listed in <Verified>',
  ]);
  assert.deepEqual(check('cd app && npm install openai@2.3.0 && npm i foo'), unpinned('npm i foo', 'foo'));
  assert.deepEqual(check('pip install openai==2.3.0 && python app.py'), []);

  // The aliases of the install commands.
  for (const command of [
    'npm i openai',
    'npm add openai',
    'pnpm i openai',
    'pnpm install openai',
    'yarn add openai',
    'bun add openai',
    'uv pip install openai',
  ]) {
    assert.deepEqual(check(command), unpinned(command), command);
  }
  for (const command of ['npm i openai@2.3.0', 'npm add openai@2.3.0', 'pnpm i openai@2.3.0', 'yarn add openai@2.3.0', 'bun add openai@2.3.0', 'uv pip install openai==2.3.0']) {
    assert.deepEqual(check(command), [], command);
  }
  // Installing a project's own dependencies names no package.
  assert.deepEqual(check('npm install\npnpm install --frozen-lockfile\nnpm i'), []);
});

