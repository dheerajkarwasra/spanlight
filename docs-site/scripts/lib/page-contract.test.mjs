const GENERATED_DIRS = ['api', 'runbooks', 'security', 'deploy'];
const GENERATED_FILES = ['changelog.md', 'reference/prices.md', 'reference/otlp-compatibility.mdx'];

function handWrittenPages() {
  const pages = [];
  const walk = (dir, prefix) => {
    for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
      const rel = prefix ? `${prefix}/${entry.name}` : entry.name;
      if (!prefix && GENERATED_DIRS.includes(entry.name)) continue;
      if (GENERATED_FILES.includes(rel)) continue;
      if (entry.isDirectory()) walk(path.join(dir, entry.name), rel);
      else if (/\.mdx?$/.test(entry.name) && rel !== 'index.mdx') {
        pages.push({ slug: rel.replace(/\.mdx?$/, ''), file: path.join(dir, entry.name) });
      }
    }
  };
  walk(DOCS, '');
  return pages.sort((a, b) => a.slug.localeCompare(b.slug));
}

const FRONTMATTER = '---\ntitle: X\ndescription: Y\n---\n';

