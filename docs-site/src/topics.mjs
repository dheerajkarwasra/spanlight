/** Every page slug listed by name in the topics (autogenerated groups are not expanded). */
export function topicSlugs(topics) {
  const slugs = [];
  const visit = (items) => {
    for (const item of items) {
      if (typeof item === 'string') slugs.push(item);
      else if (item.slug) slugs.push(item.slug);
      else if (item.items) visit(item.items);
    }
  };
  for (const topic of topics) visit(topic.items);
  return slugs;
}
