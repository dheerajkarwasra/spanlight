"""Seed a Spanlight database for the load tests.

Creates an organization, an owner, a project, one ingest key (`ingest:write`) and ten read keys
(`traces:read`), then stores spans through the real ingestion pipeline, in this process, in
batches of 1 000. Calling `app.ingest.pipeline.ingest_spans` (validate, normalize, price, upsert)
means the rows are exactly what the API would have stored, laid out in time order (batches go
oldest first, see `seed_data.py`). It skips HTTP on purpose: the ingest limit of 50 requests a
second per key would turn 10 million spans into hours of waiting, and the load test would then
measure the seeder instead of the server.

With --processes N, N processes store the batches in parallel, each taking every N-th batch, so
all of them move through the 28 days together and the rows stay roughly in time order. One
process runs at about one CPU core, so this is what makes 100 million spans a matter of hours.

It prints its rate every million spans and stops early when the seed is projected to take longer
than --max-minutes. Afterwards it builds the hourly rollups, runs VACUUM ANALYZE and prints the
table sizes and the free disk. The credentials are written to a JSON file only the current user can
read and are never printed.

    cd backend
    export LOAD_DATABASE_URL=postgresql+psycopg://postgres:...@127.0.0.1:55433/spanlight
    uv run python load/seed.py --spans 100000 --credentials-file ../.local/load/credentials.json

Connect as the database owner (the `postgres` user of the Compose stack). This is a test harness,
not a product path, so it does not go through the row-level security of the application role.

The data is generated by `seed_data.py` and the workspace created by `seed_workspace.py`, which
sit beside this file (running it as a script puts this directory on the import path).
"""

