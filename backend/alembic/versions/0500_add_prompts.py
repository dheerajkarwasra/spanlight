"""Add the prompt registry: prompts, their immutable versions and their movable labels, and allow
the audit actions of prompts, scores, datasets, annotation queues, evaluators and experiments.

Revision ID: 0500
Revises: 0405
Create Date: 2026-10-10

A prompt is a named template in a project. Every edit creates a new version; a version never
changes once written, so a span linked to a version always shows the template that produced it.
Labels (`production`, `staging` or any other name) point at one version each and move freely;
`latest` is implicit (the highest version) and cannot be stored as a label. ADR 0014 explains
the split.

Choices worth knowing about:

* The ids are UUIDv7 generated by the application, so the columns have no default. `prompts`
  carries `project_id` and cascades from `projects`; versions and labels cascade from their
  prompt, so deleting a project or a prompt deletes everything under it.
* Names repeat the API's rules by CHECK: a prompt name is `/`-separated segments
  (`judges/relevance`), each starting with a letter or digit, so no segment is empty, `.` or `..`
  and a URL path never changes its meaning; a label is lower-case and
  `latest` is reserved. `UNIQUE (project_id, name)` serves lookups by name.
* `prompts.updated_at` moves when a version is added or a label moves, so the list can be
  ordered by recent activity; `(project_id, updated_at DESC, id DESC)` serves its keyset.
* `prompt_versions.template` is `{"kind": "text", "text": ...}` or `{"kind": "chat",
  "messages": [...]}`. The `kind` column duplicates `template.kind` so it can be filtered and
  compared cheaply, and a CHECK keeps the two equal. `variables` is filled by the server from the
  template. `model_config` is a JSON object of advice for clients, at most 2 KB.
* `UNIQUE (prompt_id, id)` on versions is the target of the composite key from
  `prompt_labels (prompt_id, version_id)`, so a label can never point at another prompt's
  version. `UNIQUE (prompt_id, version)` numbers the versions and serves lookups by prompt.
* The trigger `prompt_versions_immutable` refuses every `UPDATE` of a version, with one
  exception: `created_by` becoming NULL alone, which is what `ON DELETE SET NULL` does when the
  author's account is deleted. Without it, deleting a user who wrote a version would fail.
  Deleting a version (through its prompt's cascade) is a `DELETE`, which the trigger does not see.
* `created_by` and `updated_by` are `ON DELETE SET NULL`: removing a person keeps what they
  wrote. Their indexes are partial, like the other `*_by` columns.
* Row-level security: `prompts` has the policy pair every project-scoped table has, in the
  InitPlan form of 0017. Versions and labels have no `project_id`; their isolation policy checks
  the parent prompt's project through `EXISTS`, and they have the same worker bypass.

`audit_events.action` is a CHECK over a fixed list, so it is dropped and added again with every
action allowed so far plus all the Phase 5 actions at once (prompts, score configs, datasets,
annotation queues, evaluators, experiments), as in 0402, so the later Phase 5 migrations do not
rebuild it again. `audit_events` is locked briefly; the wait for the lock is capped at 5 seconds
(`SET LOCAL lock_timeout`, as in 0402), so a long transaction fails the migration instead of
queueing every request behind it. If it times out, run it again.

Downgrade deletes the audit events that use the new actions, which the older constraint would
reject, restores the previous list, and drops the tables, the trigger function and the type. The
prompts and their history are gone with them.
"""

