def _create_prompts() -> None:
    op.execute(
        r"""
        CREATE TABLE prompts (
            id           uuid PRIMARY KEY,
            project_id   uuid NOT NULL REFERENCES projects (id) ON DELETE CASCADE,
            name         text NOT NULL
                CHECK (name ~ '^[A-Za-z0-9][A-Za-z0-9_.-]*(/[A-Za-z0-9][A-Za-z0-9_.-]*)*$'
                       AND char_length(name) <= 128),
            description  text CHECK (char_length(description) <= 1000),
            created_by   uuid REFERENCES users (id) ON DELETE SET NULL,
            created_at   timestamptz NOT NULL DEFAULT now(),
            updated_at   timestamptz NOT NULL DEFAULT now(),
            CONSTRAINT prompts_project_name_key UNIQUE (project_id, name)
        )
        """
    )
    op.execute(
        "CREATE INDEX prompts_project_updated_idx ON prompts (project_id, updated_at DESC, id DESC)"
    )
    op.execute(
        "CREATE INDEX prompts_created_by_idx ON prompts (created_by) WHERE created_by IS NOT NULL"
    )


def _create_prompt_versions() -> None:
    op.execute(
        """
        CREATE TABLE prompt_versions (
            id              uuid PRIMARY KEY,
            prompt_id       uuid NOT NULL REFERENCES prompts (id) ON DELETE CASCADE,
            version         integer NOT NULL CHECK (version >= 1),
            kind            prompt_kind NOT NULL,
            template        jsonb NOT NULL CHECK (jsonb_typeof(template) = 'object'),
            variables       text[] NOT NULL DEFAULT '{}',
            model_config    jsonb NOT NULL DEFAULT '{}'
                CHECK (jsonb_typeof(model_config) = 'object'
                       AND octet_length(model_config::text) <= 2048),
            commit_message  text CHECK (char_length(commit_message) <= 500),
            created_by      uuid REFERENCES users (id) ON DELETE SET NULL,
            created_at      timestamptz NOT NULL DEFAULT now(),
            CONSTRAINT prompt_versions_prompt_version_key UNIQUE (prompt_id, version),
            CONSTRAINT prompt_versions_prompt_id_key UNIQUE (prompt_id, id),
            CONSTRAINT prompt_versions_kind_matches_template
                CHECK (template ->> 'kind' = kind::text)
        )
        """
    )
    op.execute(
        "CREATE INDEX prompt_versions_created_by_idx ON prompt_versions (created_by) "
        "WHERE created_by IS NOT NULL"
    )


def _create_prompt_labels() -> None:
    op.execute(
        """
        CREATE TABLE prompt_labels (
            prompt_id   uuid NOT NULL REFERENCES prompts (id) ON DELETE CASCADE,
            label       text NOT NULL CHECK (label ~ '^[a-z0-9][a-z0-9_-]{0,31}$'),
            version_id  uuid NOT NULL,
            updated_by  uuid REFERENCES users (id) ON DELETE SET NULL,
            updated_at  timestamptz NOT NULL DEFAULT now(),
            PRIMARY KEY (prompt_id, label),
            CONSTRAINT prompt_labels_latest_reserved CHECK (label <> 'latest'),
            CONSTRAINT prompt_labels_version_fkey FOREIGN KEY (prompt_id, version_id)
                REFERENCES prompt_versions (prompt_id, id) ON DELETE CASCADE
        )
        """
    )
    op.execute("CREATE INDEX prompt_labels_version_idx ON prompt_labels (version_id)")
    op.execute(
        "CREATE INDEX prompt_labels_updated_by_idx ON prompt_labels (updated_by) "
        "WHERE updated_by IS NOT NULL"
    )


def _create_immutability_trigger() -> None:
    op.execute(
        """
        CREATE FUNCTION prompt_versions_immutable() RETURNS trigger
        LANGUAGE plpgsql AS $$
        BEGIN
            -- The one update allowed: ON DELETE SET NULL clearing the author of a deleted user.
            IF NEW.created_by IS NULL
               AND (NEW.id, NEW.prompt_id, NEW.version, NEW.kind, NEW.template, NEW.variables,
                    NEW.model_config, NEW.commit_message, NEW.created_at)
                   IS NOT DISTINCT FROM
                   (OLD.id, OLD.prompt_id, OLD.version, OLD.kind, OLD.template, OLD.variables,
                    OLD.model_config, OLD.commit_message, OLD.created_at)
            THEN
                RETURN NEW;
            END IF;
            RAISE EXCEPTION 'prompt versions are immutable; create a new version instead'
                USING ERRCODE = 'restrict_violation';
        END;
        $$
        """
    )
    op.execute(
        "CREATE TRIGGER prompt_versions_immutable BEFORE UPDATE ON prompt_versions "
        "FOR EACH ROW EXECUTE FUNCTION prompt_versions_immutable()"
    )


def _enable_project_row_level_security(table: str) -> None:
    op.execute(f"ALTER TABLE {table} ENABLE ROW LEVEL SECURITY")
    op.execute(f"ALTER TABLE {table} FORCE ROW LEVEL SECURITY")
    op.execute(
        f"CREATE POLICY {table}_project_isolation ON {table} "
        f"USING ({PROJECT_EXPRESSION}) WITH CHECK ({PROJECT_EXPRESSION})"
    )
    _create_bypass_policy(table)


def _enable_child_row_level_security(table: str) -> None:
    # The parent's row is read under its own policy too, so this only ever matches a prompt of
    # the bound project.
    parent_expression = (
        f"EXISTS (SELECT 1 FROM prompts p WHERE p.id = {table}.prompt_id "
        f"AND p.project_id = {PROJECT_ID})"
    )
    op.execute(f"ALTER TABLE {table} ENABLE ROW LEVEL SECURITY")
    op.execute(f"ALTER TABLE {table} FORCE ROW LEVEL SECURITY")
    op.execute(
        f"CREATE POLICY {table}_project_isolation ON {table} "
        f"USING ({parent_expression}) WITH CHECK ({parent_expression})"
    )
    _create_bypass_policy(table)


def _create_bypass_policy(table: str) -> None:
    op.execute(
        f"CREATE POLICY {table}_worker_bypass ON {table} "
        f"USING ({BYPASS_EXPRESSION}) WITH CHECK ({BYPASS_EXPRESSION})"
    )


def _set_audit_actions(actions: tuple[str, ...]) -> None:
    listed = ", ".join(f"'{action}'" for action in actions)
    op.execute("ALTER TABLE audit_events DROP CONSTRAINT audit_events_action_check")
    op.execute(
        "ALTER TABLE audit_events ADD CONSTRAINT audit_events_action_check "
        f"CHECK (action IN ({listed}))"
    )
