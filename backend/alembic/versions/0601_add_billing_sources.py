"""Add billing sources, their project mappings, fetch runs and provider cost lines.

Revision ID: 0601
Revises: 0600
Create Date: 2026-10-15

A billing source is an organization's view of one provider account: an Anthropic Admin API key,
an OpenAI Costs API key, or CSV exports uploaded by hand. Each fetch or upload is a run, and
every line the provider reported is a row keyed by the hash of its identity, so the same line
fetched twice updates one row. The reconciliation report compares those lines with Spanlight's
own figures for the projects the source is mapped to.

Choices worth knowing about:

* Ids are UUIDv7 generated by the application, so no id column has a default.
* `billing_sources` is scoped to an organization, not a project, so it has no row-level
  security: every query filters by `org_id`, as `provider_credentials` does. The admin key is
  sealed with `app.core.crypto`; `ciphertext` and `key_id` are set together or not at all, and
  exactly the API kinds carry one (a CSV source never does). The kind fixes the provider for the
  two API kinds; a CSV source names its own. `status` and `last_error` record the latest fetch;
  `last_error` is a status line, never a response body. `UNIQUE (org_id, name)` leads with
  `org_id`, so it also serves the per-organization list and the foreign key. `UNIQUE (id,
  org_id)` and `UNIQUE (id, provider)` exist only as the targets of the composite foreign keys
  below.
* `billing_source_projects` maps a source to the projects it covers. Its foreign keys carry the
  organization and the provider along: `(source_id, org_id)` and `(project_id, org_id)` make a
  source mapped to another organization's project unrepresentable, and `(source_id, provider)`
  keeps the row's provider the source's own, so `UNIQUE (project_id, provider)` means one
  account per provider per project. `projects` gains `UNIQUE (id, org_id)` as the target; the
  table has at most thousands of rows, so the index builds in the migration transaction. The
  table carries `project_id` without row-level security, because it is read only through its
  source's `org_id` and holds no telemetry; the policy inventory test lists it as the exception.
* `billing_fetch_runs` is one row per fetch or upload: who or what started it, the window of UTC
  days, the outcome and the counts. `(source_id, started_at DESC)` serves the runs listing and
  the "is a run still running" check. `requested_by` is indexed so removing a user does not scan
  the table.
* `provider_cost_lines` is one row per provider line per UTC day. `line_key` is the SHA-256
  (64 lower-case hex digits) of the line's identity, computed by the mapper, and `UNIQUE
  (source_id, day, line_key)` is the upsert target. `amount_usd` is never negative except on a
  credit. `(source_id, provider)` references the source as it does on the mapping table, so a
  line's provider is always its source's. `fetch_run_id` is `ON DELETE RESTRICT`: the run that
  wrote a line is part of its provenance, and runs are only ever removed with their source,
  which cascades to the lines first. `(source_id, day)` serves the report, `(org_id, day)`
  retention and the per-organization totals, and `(fetch_run_id)` the restrict check.
* `audit_events.action` is a CHECK over a fixed list, so it is dropped and added again with the
  six billing source actions, as in 0500.

The migration is one transaction of new tables, one small unique index on `projects` and the
CHECK swap, under a 5 s lock timeout. Downgrade removes the audit events the old CHECK rejects,
restores it, and drops the tables and the `projects` constraint.
"""

