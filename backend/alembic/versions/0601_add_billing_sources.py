def _create_billing_sources() -> None:
    op.execute(
        """
        CREATE TABLE billing_sources (
            id              uuid PRIMARY KEY,
            org_id          uuid NOT NULL REFERENCES organizations (id) ON DELETE CASCADE,
            kind            text NOT NULL
                CONSTRAINT billing_sources_kind_check
                CHECK (kind IN ('anthropic_admin_api', 'openai_costs_api', 'csv_upload')),
            provider        text NOT NULL
                CONSTRAINT billing_sources_provider_check
                CHECK (provider IN ('anthropic', 'openai', 'google')),
            name            text NOT NULL
                CONSTRAINT billing_sources_name_check
                CHECK (char_length(name) BETWEEN 1 AND 128),
            ciphertext      bytea,
            key_id          text,
            provider_scope  text
                CONSTRAINT billing_sources_provider_scope_check
                CHECK (char_length(provider_scope) <= 128),
            enabled         boolean NOT NULL DEFAULT true,
            status          text NOT NULL DEFAULT 'never_fetched'
                CONSTRAINT billing_sources_status_check
                CHECK (status IN ('never_fetched', 'ok', 'failing')),
            last_fetched_at timestamptz,
            last_success_at timestamptz,
            last_error      text
                CONSTRAINT billing_sources_last_error_check
                CHECK (char_length(last_error) <= 200),
            created_by      uuid REFERENCES users (id) ON DELETE SET NULL,
            created_at      timestamptz NOT NULL DEFAULT now(),
            updated_at      timestamptz NOT NULL DEFAULT now(),
            CONSTRAINT billing_sources_org_id_name_key UNIQUE (org_id, name),
            CONSTRAINT billing_sources_id_org_id_key UNIQUE (id, org_id),
            CONSTRAINT billing_sources_id_provider_key UNIQUE (id, provider),
            CONSTRAINT billing_sources_kind_provider_check CHECK (
                kind = 'csv_upload'
                OR (kind = 'anthropic_admin_api' AND provider = 'anthropic')
                OR (kind = 'openai_costs_api' AND provider = 'openai')
            ),
            CONSTRAINT billing_sources_ciphertext_key_id_check CHECK (
                (ciphertext IS NULL) = (key_id IS NULL)
            ),
            CONSTRAINT billing_sources_kind_ciphertext_check CHECK (
                (kind = 'csv_upload') = (ciphertext IS NULL)
            )
        )
        """
    )
    op.execute("CREATE INDEX billing_sources_created_by_idx ON billing_sources (created_by)")


def _create_billing_source_projects() -> None:
    op.execute(
        """
        CREATE TABLE billing_source_projects (
            source_id   uuid NOT NULL,
            project_id  uuid NOT NULL,
            org_id      uuid NOT NULL,
            provider    text NOT NULL,
            CONSTRAINT billing_source_projects_pkey PRIMARY KEY (source_id, project_id),
            CONSTRAINT billing_source_projects_source_id_org_id_fkey
                FOREIGN KEY (source_id, org_id)
                REFERENCES billing_sources (id, org_id) ON DELETE CASCADE,
            CONSTRAINT billing_source_projects_source_id_provider_fkey
                FOREIGN KEY (source_id, provider)
                REFERENCES billing_sources (id, provider) ON DELETE CASCADE,
            CONSTRAINT billing_source_projects_project_id_org_id_fkey
                FOREIGN KEY (project_id, org_id)
                REFERENCES projects (id, org_id) ON DELETE CASCADE,
            CONSTRAINT billing_source_projects_project_id_provider_key
                UNIQUE (project_id, provider)
        )
        """
    )
    op.execute(
        "CREATE INDEX billing_source_projects_project_id_idx "
        "ON billing_source_projects (project_id)"
    )


def _create_billing_fetch_runs() -> None:
    op.execute(
        """
        CREATE TABLE billing_fetch_runs (
            id              uuid PRIMARY KEY,
            source_id       uuid NOT NULL,
            org_id          uuid NOT NULL,
            trigger         text NOT NULL
                CONSTRAINT billing_fetch_runs_trigger_check
                CHECK (trigger IN ('scheduled', 'manual', 'csv_upload')),
            day_from        date NOT NULL,
            day_to          date NOT NULL,
            status          text NOT NULL
                CONSTRAINT billing_fetch_runs_status_check
                CHECK (status IN ('running', 'ok', 'failed')),
            error           text
                CONSTRAINT billing_fetch_runs_error_check CHECK (char_length(error) <= 200),
            lines_upserted  integer NOT NULL DEFAULT 0,
            pages           integer NOT NULL DEFAULT 0,
            requested_by    uuid REFERENCES users (id) ON DELETE SET NULL,
            started_at      timestamptz NOT NULL DEFAULT now(),
            finished_at     timestamptz,
            CONSTRAINT billing_fetch_runs_source_id_org_id_fkey
                FOREIGN KEY (source_id, org_id)
                REFERENCES billing_sources (id, org_id) ON DELETE CASCADE,
            CONSTRAINT billing_fetch_runs_day_range_check CHECK (day_from <= day_to)
        )
        """
    )
    op.execute(
        "CREATE INDEX billing_fetch_runs_source_id_started_at_idx "
        "ON billing_fetch_runs (source_id, started_at DESC)"
    )
    op.execute(
        "CREATE INDEX billing_fetch_runs_requested_by_idx ON billing_fetch_runs (requested_by)"
    )


def _create_provider_cost_lines() -> None:
    op.execute(
        """
        CREATE TABLE provider_cost_lines (
            id              uuid PRIMARY KEY,
            source_id       uuid NOT NULL,
            org_id          uuid NOT NULL,
            fetch_run_id    uuid NOT NULL REFERENCES billing_fetch_runs (id) ON DELETE RESTRICT,
            day             date NOT NULL,
            provider        text NOT NULL,
            line_key        text NOT NULL
                CONSTRAINT provider_cost_lines_line_key_check
                CHECK (line_key ~ '^[0-9a-f]{64}$'),
            line_kind       text NOT NULL
                CONSTRAINT provider_cost_lines_line_kind_check
                CHECK (line_kind IN ('tokens', 'web_search', 'code_execution', 'credit', 'other')),
            model_raw       text
                CONSTRAINT provider_cost_lines_model_raw_check
                CHECK (char_length(model_raw) <= 256),
            model_pattern   text,
            token_type      text
                CONSTRAINT provider_cost_lines_token_type_check
                CHECK (token_type IN ('uncached_input', 'cache_read', 'cache_write_5m',
                                      'cache_write_1h', 'output', 'input', 'cached_input')),
            service_tier    text
                CONSTRAINT provider_cost_lines_service_tier_check
                CHECK (service_tier IN ('standard', 'batch', 'priority', 'flex')),
            context_window  text,
            provider_scope  text,
            description     text NOT NULL
                CONSTRAINT provider_cost_lines_description_check
                CHECK (char_length(description) <= 512),
            quantity        bigint,
            amount_usd      numeric(14, 8) NOT NULL,
            first_seen_at   timestamptz NOT NULL,
            last_seen_at    timestamptz NOT NULL,
            CONSTRAINT provider_cost_lines_source_id_org_id_fkey
                FOREIGN KEY (source_id, org_id)
                REFERENCES billing_sources (id, org_id) ON DELETE CASCADE,
            CONSTRAINT provider_cost_lines_source_id_provider_fkey
                FOREIGN KEY (source_id, provider)
                REFERENCES billing_sources (id, provider) ON DELETE CASCADE,
            CONSTRAINT provider_cost_lines_source_id_day_line_key_key
                UNIQUE (source_id, day, line_key),
            CONSTRAINT provider_cost_lines_amount_usd_check
                CHECK (line_kind = 'credit' OR amount_usd >= 0)
        )
        """
    )
    op.execute(
        "CREATE INDEX provider_cost_lines_source_id_day_idx ON provider_cost_lines (source_id, day)"
    )
    op.execute(
        "CREATE INDEX provider_cost_lines_org_id_day_idx ON provider_cost_lines (org_id, day)"
    )
    op.execute(
        "CREATE INDEX provider_cost_lines_fetch_run_id_idx ON provider_cost_lines (fetch_run_id)"
    )


